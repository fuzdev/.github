/**
 * Generates the fuzdev org profile, rendered at github.com/fuzdev, from the
 * stack data behind fuz.dev's `/stack` page. The data is imported straight
 * from the sibling fuz.dev checkout so the two never disagree about what
 * exists; this file owns only the GitHub-flavored presentation. Run with
 * `gro gen profile/README.gen.md.ts` from the repo root.
 *
 * @module
 */

import type { Gen } from '@fuzdev/gro/gen.ts';

import {
	stack_layers,
	foundation_groups,
	STACK_LANGUAGES,
	STACK_STATUSES,
	type StackLanguage,
	type StackPiece,
	type StackStatus
} from '../../fuz.dev/src/routes/stack/stack.ts';

const FUZ_DEV_URL = 'https://www.fuz.dev';
const ORG_URL = 'https://github.com/fuzdev';
const INTRO_POST_URL = `${FUZ_DEV_URL}/blog/1-fuz-is-a-free-software-stack-for-human-agency`;
const LICENSE_URL = 'https://opensource.org/license/0bsd';
const DISCUSSIONS_URL = 'https://github.com/orgs/fuzdev/discussions';
const HEALTH_FILES_URL = `${ORG_URL}/.github/blob/main`;

const SEP = ' · ';

/** Renders a status or language as a code span, GitHub's closest thing to a chip. */
const chip = (label: string): string => `\`${label}\``;

/** The short host of a docs site, for a compact trailing link: `css.fuz.dev`. */
const site_label = (url: string): string => new URL(url).host;

const render_piece = (piece: StackPiece): string => {
	const chips = [
		chip(STACK_STATUSES[piece.status].label),
		...piece.languages.map((language) => chip(language))
	].join(' ');
	const parts = [`**[${piece.name}](${piece.repo})**`, piece.tagline, chips];
	if (piece.site) parts.push(`[${site_label(piece.site)}](${piece.site})`);
	return `- ${parts.join(SEP)}`;
};

/** @nodocs */
export const gen: Gen = {
	generate: ({ origin_path }) => {
		// legend shows only the tiers in use, in declaration order, like the site
		const used_statuses = (Object.keys(STACK_STATUSES) as Array<StackStatus>).filter((status) =>
			stack_layers.some((layer) => layer.pieces.some((p) => p.status === status))
		);
		const languages = Object.keys(STACK_LANGUAGES) as Array<StackLanguage>;

		const sections: Array<string> = [];

		sections.push(`<!-- generated by ${origin_path} from fuz.dev's stack data -- DO NOT EDIT DIRECTLY! -->

<img src="logo.svg" alt="a friendly brown spider facing you" align="right" width="160" height="160">

# Fuz

Fuz ([fuz.dev](${FUZ_DEV_URL}/)) is a free software stack designed for human agency:
it provides tools and libraries in TypeScript, CSS, Svelte, and Rust, building on
open web and native foundations.
It bakes in some opinions but is designed for modularity, so you can use a
single piece or whichever parts fit your project. All of the code is licensed
with the public-domain-equivalent [0BSD](${LICENSE_URL}).
For the story behind it, read the [intro post](${INTRO_POST_URL}).

Everything is pre-1.0 and changes without deprecation. Each piece below is
marked by where it stands:

${used_statuses.map((status) => `- ${chip(STACK_STATUSES[status].label)} ${STACK_STATUSES[status].description}`).join('\n')}

and what it's made of:

${languages.map((language) => `- ${chip(language)} ${STACK_LANGUAGES[language].description}`).join('\n')}`);

		sections.push(`## the stack

From what you make down to what it's made of. The same map lives at
[fuz.dev/stack](${FUZ_DEV_URL}/stack); names link to the repos, and the trailing
link is the project's docs site.`);

		for (const layer of stack_layers) {
			sections.push(`### ${layer.name}

${layer.blurb}

${layer.pieces.map(render_piece).join('\n')}`);
		}

		sections.push(`## what it rests on

Open technologies Fuz builds on, none of them Fuz's own.

${foundation_groups
	.map((group) =>
		[`**${group.name}**`, group.items.join(', '), ...(group.blurb ? [group.blurb] : [])].join(SEP)
	)
	.map((line) => `- ${line}`)
	.join('\n')}`);

		sections.push(`## more

[fuz.dev](${FUZ_DEV_URL}/)${SEP}[contributing](${FUZ_DEV_URL}/contributing)${SEP}[discussions](${DISCUSSIONS_URL})${SEP}[security](${HEALTH_FILES_URL}/SECURITY.md)${SEP}[code of conduct](${HEALTH_FILES_URL}/CODE_OF_CONDUCT.md)`);

		return { content: sections.join('\n\n') + '\n', format: false };
	},
	inputs: { files: ['../fuz.dev/src/routes/stack/stack.ts'] }
};
